"""prereg_amend_5 §3 descriptor: verdict and per-leg catch curves on C-sp and C-gene at a = .3 / .6 / .9 (V-AAL, V-DK).

Registered descriptor, not a gate. From the existing replayed plant files (artifacts/plants/<cell>.csv.gz with
a3species_<cell>.csv.gz, e3_species_replay.py) by amendment 3 §5's catch rule, exactly as e3_gates_a3.py computes the
a = .9 verdict catch: plants never generated (status != ok) excluded by the frozen convention; every other plant in the
denominator; any verdict status other than ok = a miss. Reported beside it: each leg's own rate (Level 0, the stratified
site leg, G1, G3m, G6s, G6l, the species max) and the Level 0 ∧ site conjunction, at alpha_v = .025. It first asserts that
a = .9 reproduces amendment 5 §1 / §3 exactly (C-gene 197 / 296 and 175 / 299; C-sp 291 / 300 in both classes); a mismatch
stops it. Writes arcs/audit/results/e3_catch_curves_a5.json and .md.
Run: env\\venv\\Scripts\\python.exe -X utf8 arcs\\audit\\src\\e3_catch_curves_a5.py
"""
from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import e3_gates_a3 as G  # noqa: E402

A = [0.3, 0.6, 0.9]
FAMS = ["C-sp", "C-gene"]
LEGS = {"level0": "p_naive", "site": "p_L1_strat", "G1": "p_G1c", "G3m": "p_G3m", "G6s": "p_G6s", "G6l": "p_G6l",
        "species": "p_species"}
EXPECT_A9 = {("aal", "C-gene"): (197, 296), ("dk", "C-gene"): (175, 299), ("aal", "C-sp"): (291, 300),
             ("dk", "C-sp"): (291, 300)}  # amendment 5 §1 / §3


def curve(c: str, fam: str, a: float) -> dict:
    d = G.load_existing(f"{c}_{fam}_m25_a{a:g}")
    if d is None:
        raise SystemExit(f"missing plant file for {c} {fam} a={a:g}")
    d = d[d["status"] == "ok"]  # frozen convention (as e3_gates_a3.py): plants never generated stay excluded
    g = G.rate_gate(d, "p_verdict_a3", f"VERDICT CATCH {c} {fam} a={a:g}", "catch", floor=G.CATCH,
                    computed_only=False, status_col="verdict_status_a3")
    n = len(d)
    legs = {k: int((d[col] < G.ALPHA_V).sum()) for k, col in LEGS.items()}
    legs["level0_and_site"] = int(((d["p_naive"] < G.ALPHA_V) & (d["p_L1_strat"] < G.ALPHA_V)).sum())
    return dict(cls=c, family=fam, a=a, k=g["k"], n=g["n"], rate=g["rate"], by_step=g["by_step"],
                status_counts=g.get("status_counts"), legs={k: dict(k=v, n=n, rate=v / n) for k, v in legs.items()})


def main():
    rows = [curve(c, f, a) for c in G.CATCH_CLASSES for f in FAMS for a in A]
    for r in rows:
        if r["a"] == 0.9 and (r["k"], r["n"]) != EXPECT_A9[(r["cls"], r["family"])]:
            raise SystemExit(f"a = .9 does not reproduce amendment 5: {r['cls']} {r['family']} {r['k']} / {r['n']} vs "
                             f"{EXPECT_A9[(r['cls'], r['family'])]}")
    out = dict(amendment="prereg_amend_5 §3 (registered descriptor; not a gate)", alpha_v=G.ALPHA_V,
               a9_reproduces_amendment_5=True, curves=rows, inputs_sha256=G.INPUTS,
               script_sha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
               commit=G.git("rev-parse", "HEAD"), dirty=bool(G.git("status", "--porcelain")))
    G.RES.mkdir(parents=True, exist_ok=True)
    (G.RES / "e3_catch_curves_a5.json").write_text(json.dumps(out, indent=1, default=float), encoding="utf-8")
    L = [f"# Catch curves under amendment 5 §3 — GENERATED by e3_catch_curves_a5.py @ {out['commit'][:7]}; "
         "do not hand-edit", "",
         "Registered descriptor (not a gate). Rates at alpha_v = .025; a = .9 asserted equal to amendment 5 §1 / §3.", "",
         "| class | plant | a | verdict k / n | verdict | Level 0 | site | Level 0 ∧ site | G1 | G3m | G6s | G6l | species |",
         "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        lg = r["legs"]
        L.append(f"| {r['cls']} | {r['family']} | {r['a']:g} | {r['k']} / {r['n']} | {r['rate']:.3f} | "
                 + " | ".join(f"{lg[k]['rate']:.3f}" for k in ("level0", "site", "level0_and_site", "G1", "G3m", "G6s",
                                                               "G6l", "species")) + " |")
    (G.RES / "e3_catch_curves_a5.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    for x in L[6:]:
        print(x)


if __name__ == "__main__":
    main()
