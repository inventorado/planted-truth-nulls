"""ASDG-AUD-E5-regime: every cell of the probe as generated tables (probe prereg §4-§5: all cells reported).

Reads results/regime_A.json (spaces A / A' / A'') and results/regime_B.json (space B replay); writes
results/regime_cells.md:
1. every cell: rejection rate at .05 and .025, the 99 % CI at .05, the three-way class at both levels, matched and
   unmatched set counts (space B also by class-step stratum);
2. O2: every per-map Moran's I fit (B1, B2, pooled): slope, intercept, r, the Moran's I at which the fit crosses .05,
   and whether that crossing lies inside the data;
3. O3: every per-set coherence fit: the same quantities, with coherence in place of Moran's I;
4. O5 and the realised set properties: per space × set type × m, the realised coherence (min, q10, median, q90, max),
   S's coexpression z against 2,000 random sets (the reach "target z"), N2's accepted counts, N3's status counts, and
   the coherence of the sets N2 could match;
5. P4 (power descriptor): every statistic × null × score variant.
Cell keys use " · " in place of the JSON's "|" so the tables render. Nothing is recomputed.
Run (programme root): env\\venv\\Scripts\\python.exe -X utf8 arcs\\audit\\probes\\regime\\src\\regime_report.py
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
RES = HERE.parent / "results"


def key(k: str) -> str:
    return k.replace("|", " · ")


def num(x, nd=4) -> str:
    if x is None or (isinstance(x, float) and x != x):
        return "—"
    return f"{x:.{nd}f}" if isinstance(x, float) else str(x)


def rate(a) -> str:
    if not a or a.get("cls") == "not computed" or a.get("rate") != a.get("rate"):
        return "not computed"
    return f"{a['rate']:.4f}"


def ci(a) -> str:
    return "—" if not a or not a.get("ci99") else f"[{a['ci99'][0]:.3f}, {a['ci99'][1]:.3f}]"


def fitrow(name: str, f) -> str:
    if not f:
        return f"| {name} | — | — | — | — | — |"
    return (f"| {name} | {num(f['slope'], 3)} | {num(f['intercept'], 4)} | {num(f['r'], 3)} | "
            f"{num(f['cross_05'], 4)} | {'inside' if f['cross_inside_data'] else 'outside'} |")


def main():
    pa, pb = RES / "regime_A.json", RES / "regime_B.json"
    A, B = json.loads(pa.read_text(encoding="utf-8")), json.loads(pb.read_text(encoding="utf-8"))
    out = ["# ASDG-AUD-E5-regime — every cell (GENERATED by `src/regime_report.py`; do not hand-edit)", "",
           f"Inputs: `regime_A.json` sha256 {hashlib.sha256(pa.read_bytes()).hexdigest()[:16]}… (commit "
           f"{A['commit'][:7]}, dirty {A['dirty']}); `regime_B.json` sha256 "
           f"{hashlib.sha256(pb.read_bytes()).hexdigest()[:16]}… (commit {B['commit'][:7]}, dirty {B['dirty']}: only "
           "`results/regime_A.json` was untracked when it ran). Class rule (prereg §4): anticonservative iff the 99 % "
           "CI lower bound > .05 and rate > .07; calibrated iff upper ≤ .07 and rate ≤ .06; else indeterminate.", "",
           "## 1. Every cell — spaces A / A′ / A″", "",
           "Cell = space · set type · m · map family · null · statistic; n_sets = matched sets.", "",
           "| cell | n_sets | unmatched | rate .05 | 99 % CI .05 | class .05 | rate .025 | class .025 |",
           "|---|---|---|---|---|---|---|---|"]
    for k, v in A["cells"].items():
        a, b = v.get("a0.05"), v.get("a0.025")
        out.append(f"| {key(k)} | {v.get('n_sets')} | {v.get('n_unmatched')} | {rate(a)} | {ci(a)} | "
                   f"{(a or {}).get('cls', '—')} | {rate(b)} | {(b or {}).get('cls', '—')} |")
    out += ["", "## 1b. Every cell — space B (E3 V-DK replay)", "",
            "| plant family | null · statistic | unmatched | rate .05 | 99 % CI .05 | class .05 | step 0 | step 1 | "
            "rate .025 | class .025 |", "|---|---|---|---|---|---|---|---|---|---|"]
    for fam, v in B["cells"].items():
        for k, x in v["results"].items():
            a, b, bs = x["a0.05"], x["a0.025"], x.get("by_step", {})
            out.append(f"| {fam} | {key(k)} | {x.get('unmatched')} | {rate(a)} | {ci(a)} | {a.get('cls')} | "
                       f"{rate(bs.get('0'))} | {rate(bs.get('1'))} | {rate(b)} | {b.get('cls')} |")
        out.append(f"| {fam} | replay {v['replay_ok']}/{v['n_plants']}; P3: {v['P3']}; N2 matched "
                   f"{v['n2_matched_frac']:.2f} | | | | | | | | |")
    out += ["", "## 2. O2 — per-map rejection rate (at .05) on Moran's I", "",
            f"Moran's I (inverse-distance weights) q10 / median / q90: B1 "
            f"{' / '.join(f'{q:.3f}' for q in A['moran_q10_50_90']['B1'])}; B2 "
            f"{' / '.join(f'{q:.3f}' for q in A['moran_q10_50_90']['B2'])}.", "",
            "| fit (space · set type · m · null · statistic · family) | slope | intercept | r | crossing of .05 | "
            "crossing |", "|---|---|---|---|---|---|"]
    for k, v in A["regressions"]["moran"].items():
        for fam in ("B1", "B2", "pooled"):
            out.append(fitrow(f"{key(k)} · {fam}", (v or {}).get(fam)))
    out += ["", "## 3. O3 — per-set rejection rate (at .05) on set coherence (A1r + A2m + A2 pooled at one m)", "",
            "| fit (space · m · map family · null · statistic) | slope | intercept | r | crossing of .05 | crossing |",
            "|---|---|---|---|---|---|"]
    for k, v in A["regressions"]["coherence"].items():
        out.append(fitrow(key(k), v))
    out += ["", "## 4. O5 — reach and realised set properties", "",
            "| space · set type · m | n | coherence min / q10 / median / q90 / max | target z median | N2 accepted = K "
            "(of n) | coherence median of N2-matched sets | N3 status |", "|---|---|---|---|---|---|---|"]
    for sk, rows in A["set_info"].items():
        ms = sorted({r["m"] for r in rows}) if not sk.endswith("|A1") else ["all"]
        for m in ms:
            rs = rows if m == "all" else [r for r in rows if r["m"] == m]
            coh = np.array([r["coexp"] for r in rs], float)
            tz = np.array([r["target_z"] for r in rs], float)
            acc = np.array([r["n2_accepted"] for r in rs], float)
            matched = coh[acc >= A["K"]]
            st = {}
            for r in rs:
                st[r["n3_status"]] = st.get(r["n3_status"], 0) + 1
            q = np.quantile(coh, [0, .1, .5, .9, 1])
            out.append(f"| {key(sk)} · m {m} | {len(rs)} | {' / '.join(f'{x:.3f}' for x in q)} | {np.median(tz):.1f} | "
                       f"{int((acc >= A['K']).sum())} | {num(float(np.median(matched)), 3) if len(matched) else '—'} | "
                       f"{', '.join(f'{k} {v}' for k, v in st.items())} |")
    p4 = A["plants"].get("P4_power_at_05", {})
    out += ["", "## 5. P4 — power at .05 on planted positives (B2 maps; descriptor)", "",
            "| space · set type · null · statistic · score variant | catch rate |", "|---|---|"]
    for k in sorted(p4):
        out.append(f"| {key(k)} | {num(p4[k], 3) if isinstance(p4[k], float) else '—'} |")
    (RES / "regime_cells.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {RES / 'regime_cells.md'}: {len(A['cells'])} + {sum(len(v['results']) for v in B['cells'].values())} "
          f"cells, {3 * len(A['regressions']['moran'])} Moran fits, {len(A['regressions']['coherence'])} coherence fits, "
          f"{len(p4)} P4 entries")


if __name__ == "__main__":
    main()
